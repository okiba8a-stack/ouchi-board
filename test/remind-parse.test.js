// node test/remind-parse.test.js
const { parseRemind } = require("../remind-parse.js");

// 基準：2026-11-13（金）10:00
const NOW = new Date(2026, 10, 13, 10, 0);
const fmt = (d) => d ? `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")} ${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}` : null;

const cases = [
  ["1週間後にパンチェッタのラップを外す", "2026-11-20 09:00", "パンチェッタのラップを外す"],
  ["一週間後にパンチェッタのラップを外すって教えて", "2026-11-20 09:00", "パンチェッタのラップを外す"],
  ["１週間後の夜8時にラップを外す", "2026-11-20 20:00", "ラップを外す"],
  ["3日後 歯医者の予約", "2026-11-16 09:00", "歯医者の予約"],
  ["明日の朝7時にゴミ出し", "2026-11-14 07:00", "ゴミ出し"],
  ["あさって15時半 荷物受け取り", "2026-11-15 15:30", "荷物受け取り"],
  ["来週の土曜にパンチェッタ", "2026-11-21 09:00", "パンチェッタ"],
  ["今週の日曜 買い出し", "2026-11-15 09:00", "買い出し"],
  ["月曜に書類を出す", "2026-11-16 09:00", "書類を出す"],
  ["11/20 19:00 ラップを外す", "2026-11-20 19:00", "ラップを外す"],
  ["12月3日に先生と面談", "2026-12-03 09:00", "先生と面談"],
  ["2時間後に洗濯物を取り込む", "2026-11-13 12:00", "洗濯物を取り込む"],
  ["30分後 パスタ", "2026-11-13 10:30", "パスタ"],
  ["1か月後にぬか床の様子を見る", "2026-12-13 09:00", "ぬか床の様子を見る"],
  ["午後3時に電話する", "2026-11-13 15:00", "電話する"],
  ["8時に起きる", "2026-11-14 08:00", "起きる"],
  ["はさみを明日買う", "2026-11-14 09:00", "はさみを買う"],
  ["牛乳を買う", null, "牛乳を買う"],
];

let fail = 0;
for (const [text, wantDate, wantTitle] of cases) {
  const r = parseRemind(text, NOW);
  const gotDate = r && r.start ? fmt(r.start) : null;
  const ok = gotDate === wantDate && r.title === wantTitle;
  if (!ok) fail++;
  console.log(`${ok ? "OK  " : "NG  "}${text}  →  ${gotDate} / ${r && r.title}${ok ? "" : `   （期待：${wantDate} / ${wantTitle}）`}`);
}
console.log(fail ? `\n${fail} 件失敗` : "\nすべて成功");
process.exit(fail ? 1 : 0);
